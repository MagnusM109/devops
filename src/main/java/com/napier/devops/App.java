    //Gets employee data and returns it as an employee class
    public Employee getEmployee(int ID)
    {
        try
        {
            // Create an SQL statement
            Statement stmt = con.createStatement();
            // Create string for SQL statement
            String strSelect =
                    "SELECT emp_no, first_name, last_name, title, salary, dept_name "
                            + "FROM employees "
                            + "JOIN titles ON emp_no = titles.emp_no"
                            + "JOIN salaries ON emp_no = salaries.emp_no"
                            + "JOIN dept_manager ON emp_no = dept_manager.emp_no"
                            + "JOIN departments ON dept_no = departments.dept_no"
                            + "WHERE emp_no = " + ID;
            // Execute SQL statement
            ResultSet rset = stmt.executeQuery(strSelect);
            // Return new employee if valid.
            // Check one is returned
            if (rset.next())
            {
                Employee emp = new Employee();
                emp.emp_no = rset.getInt("emp_no");
                emp.first_name = rset.getString("first_name");
                emp.last_name = rset.getString("last_name");
                emp.title = rset.getString("title");
                emp.dept_name = rset.getString("dept_name");
                return emp;
            }
            else
                return null;
        }
        catch (Exception e)
        {
            System.out.println(e.getMessage());
            System.out.println("Failed to get employee details");
            return null;
        }
    }

